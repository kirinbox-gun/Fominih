#!/bin/bash

# Проверка, что аргумент передан
if [ -z "$1" ]; then
  echo "Использование: $0 <путь_к_директории>"
  exit 1
fi

# Проверка, что путь существует и является директорией
if [ ! -d "$1" ]; then
  echo "Ошибка: '$1' не является директорией"
  exit 1
fi

# Перебор всех файлов в директории и поддиректориях
for file in $(find "$1" -type f); do
  size=$(stat -c%s "$file")               # Получение размера файла
  perms=$(stat -c%A "$file")              # Получение прав доступа
  echo "$file — размер: $size байт, права: $perms"
done
