#!/bin/bash
# Скрипт для удаления повторяющихся слов из строки, переданной пользователем

# Проверка наличия входного параметра
if [[ -z "$1" ]]; then
    echo "шибка: необходимо передать строку как параметр."
    echo "Пример: ./remove_repeat.sh \"ошибка ошибка — это повтор слова\""
    exit 1
fi

# Получаем входную строку
input="$1"

# 🔍 Удаляем повторяющиеся слова с пробелами между ними
# \b(\w+)\b\s+\1\b — регулярка для поиска повторов
# \1 — замена на одно слово
cleaned=$(echo "$input" | sed -E 's/\b(\w+)\b\s+\1\b/\1/g')

# Записываем результат в файл (перезапись)
echo "$cleaned" > delRepeat.txt

# Выводим подтверждение
echo "Результат записан в delRepeat.txt:"
echo "$cleaned"
